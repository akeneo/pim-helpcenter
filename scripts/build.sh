#!/usr/bin/env bash
# Builds the static help center into ./public (or $OUTPUT_DIR).
#
#   scripts/build.sh          build every version listed in build/versions.txt
#   scripts/build.sh v7 v6    build only these versions (plus the site root files)
#
# Each version is built with its own toolchain, as on its original branch: Node 10,
# its own yarn.lock (--frozen-lockfile) and `gulp create-dist`. Only Docker is required.
# --ignore-engines: the jest packages of v4 (tests only, not used by the build) declare Node >= 12.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUTPUT_DIR="${OUTPUT_DIR:-${ROOT_DIR}/public}"
WORK_DIR="${WORK_DIR:-${ROOT_DIR}/.build}"
NODE_IMAGE="${NODE_IMAGE:-node:10.24.1-alpine3.11}"
# Base URL of the links in the "updates" feed generated by each version
export HELP_CENTER_URL="${HELP_CENTER_URL:-https://help.akeneo.com/}"

declare -A OUTPUT_NAME
ALL_VERSIONS=()
while read -r version output_name; do
    ALL_VERSIONS+=("${version}")
    OUTPUT_NAME["${version}"]="${output_name}"
done < <(grep -vE '^\s*(#|$)' "${ROOT_DIR}/build/versions.txt")
LATEST="${ALL_VERSIONS[0]}"

if [[ $# -gt 0 ]]; then
    REQUESTED=("$@")
else
    REQUESTED=("${ALL_VERSIONS[@]}")
fi

for version in "${REQUESTED[@]}"; do
    if [[ -z "${OUTPUT_NAME[${version}]:-}" ]]; then
        echo "Unknown version '${version}': it is not listed in build/versions.txt" >&2
        exit 1
    fi
done

mkdir -p "${OUTPUT_DIR}/pim" "${WORK_DIR}"

for version in "${REQUESTED[@]}"; do
    output_name="${OUTPUT_NAME[${version}]}"
    echo "==> Building ${version}"
    # Build in a copy, so the sources stay clean. node_modules is kept between two builds.
    mkdir -p "${WORK_DIR}/${version}"
    tar -C "${ROOT_DIR}/versions/${version}" --exclude=./node_modules --exclude=./dist -cf - . \
        | tar -C "${WORK_DIR}/${version}" -xf -
    rm -rf "${WORK_DIR:?}/${version}/dist"
    docker run --rm \
        --user "$(id -u):$(id -g)" \
        --env HOME=/tmp \
        --env HELP_CENTER_URL \
        --volume "${WORK_DIR}/${version}:/work" \
        --workdir /work \
        "${NODE_IMAGE}" \
        sh -c 'yarn install --frozen-lockfile --ignore-engines --non-interactive --silent && yarn --silent gulp create-dist'

    if [[ ! -d "${WORK_DIR}/${version}/dist/pim/${output_name}" ]]; then
        echo "The build of ${version} did not produce dist/pim/${output_name}: check build/versions.txt" >&2
        exit 1
    fi
    rm -rf "${OUTPUT_DIR:?}/pim/${output_name}"
    cp -R "${WORK_DIR}/${version}/dist/pim/${output_name}" "${OUTPUT_DIR}/pim/${output_name}"
    # Every version generates the list of versions it knows: the newest one knows them all.
    if [[ "${version}" == "${LATEST}" ]]; then
        cp "${WORK_DIR}/${version}/dist/pim/versions.json" "${OUTPUT_DIR}/pim/versions.json"
    fi
done

echo "==> Generating the site root files"
python3 "${ROOT_DIR}/scripts/generate_site_root.py" \
    --site-dir "${ROOT_DIR}/site" \
    --output-dir "${OUTPUT_DIR}" \
    --latest-url "/pim/${OUTPUT_NAME[${LATEST}]}/index.html"

echo "Done: ${OUTPUT_DIR}"
